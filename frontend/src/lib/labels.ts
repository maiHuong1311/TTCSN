export const fieldLabel = (field: string) =>
  field
    .split('.')
    .map((part) => {
      const match = part.match(/^(\w+)\[(\d+)\]$/);
      return match
        ? (fields[match[1]] ?? match[1]) + ' ' + (Number(match[2]) + 1)
        : (fields[part] ?? part);
    })
    .join(' · ');
